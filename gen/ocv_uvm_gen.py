"""ocv_uvm_gen.py - the UVM layer of one DUT, generated from its descriptor (ocv_gen.py --uvm).

    <name>_ocv_uvm_pkg.sv      transactions (one class per channel, fields as in the descriptor,
                               compare rules in do_compare), pin-level drivers/monitors for
                               simulation, agents (ocv_uvm_pkg base classes: the same agents
                               exchange transactions with the FPGA in the board build)
    <name>_ocv_uvm_harness.sv  simulation: clock, reset, the DUT and its pins as an interface,
                               published to the agents; board build (OCV_BOARD): empty
"""


