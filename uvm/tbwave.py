#!/usr/bin/env python3
"""tbwave.py - a waveform of a failure the board found, recorded on a PC: a wrapper module around the
verifier's top (unchanged) that counts the transfers of each channel on the DUT's pins, as tbparse.py
reads them from the testbench, and writes a VCD file only around the record the board named.

The board ends a failed run with a line such as
    OCV: waveform on a PC: ... +OCV_WAVE=retire:11646
(the record's number in its channel, 1-based, as the scoreboard counts them). The same test run in
plain simulation (build_board.sh wave) with that plusarg dumps
    +OCV_WAVE_BEFORE=<records>   records of that channel before it (default 20)
    +OCV_WAVE_AFTER=<clocks>     clocks after it (default 200), then the simulation ends
    +OCV_WAVE_FILE=<file>        default ocv_wave.vcd
Several channels may be named (+OCV_WAVE=res:120,prod:118): the first to get close starts the dump.

    tbwave.py <tb.sv ...> [--top tb_top] -o <top>_wave.sv
"""
import argparse, sys

from tbparse import TbError, parse


def wrapper(d):
    top, inst, clk = d["_top"], d["_dut_instance"], d["clock"]
    chans = [c for c in d["channels"]]
    n = len(chans)
    lines = [
        f"// GENERATED by tbwave.py from {top} - the waveform around the record the board named; do not edit.",
        f"module {top}_wave;",
        f"    {top} u ();                                   // the verifier's top, as written",
        "",
        f"    localparam int N = {n};",
        f"    string   names[N] = '{{{', '.join(chr(34) + c['name'] + chr(34) for c in chans)}}};",
        "    longint  cnt[N], at[N];",
        "    bit      want[N];",
        "    int      n_before = 20, n_after = 200, n_left = -1;",
        "    bit      on = 0, armed = 0;",
        "    string   file = \"ocv_wave.vcd\";",
        "",
        "    initial begin",
        "        string s, item, nm;   // assigned in the loop (an initialiser would run once)",
        "        int k;",
        "        if ($value$plusargs(\"OCV_WAVE=%s\", s)) begin",
        "            s = {s, \",\"};",
        "            for (int i = 0, b = 0; i < s.len(); i++)",
        "                if (s[i] == \",\") begin",
        "                    item = s.substr(b, i - 1);",
        "                    b = i + 1;",
        "                    for (int j = 0; j < item.len(); j++)",
        "                        if (item[j] == \":\") begin",
        "                            nm = item.substr(0, j - 1);",
        "                            k = -1;",
        "                            for (int c = 0; c < N; c++) if (names[c] == nm) k = c;",
        "                            if (k < 0) $fatal(1, \"+OCV_WAVE: no channel '%s'\", nm);",
        "                            want[k] = 1;",
        "                            at[k] = item.substr(j + 1, item.len() - 1).atoi();",
        "                        end",
        "                end",
        "            armed = 1;",
        "        end",
        "        void'($value$plusargs(\"OCV_WAVE_BEFORE=%d\", n_before));",
        "        void'($value$plusargs(\"OCV_WAVE_AFTER=%d\", n_after));",
        "        void'($value$plusargs(\"OCV_WAVE_FILE=%s\", file));",
        "    end",
        "",
        "    // a transfer: valid (and ready) at a rising clock edge, as the testbench's monitor sees it",
        f"    always @(posedge u.{inst}.{clk}) if (armed) begin",
    ]
    for i, c in enumerate(chans):
        cond = f"u.{inst}.{c['valid']}" + (f" && u.{inst}.{c['ready']}" if c.get("ready") else "")
        lines.append(f"        if ({cond}) cnt[{i}]++;")
    lines += [
        "        for (int c = 0; c < N; c++) begin",
        "            if (want[c] && !on && cnt[c] + n_before >= at[c]) begin",
        "                $dumpfile(file);",
        "                $dumpvars(0, u);",
        "                on = 1;",
        "                $display(\"OCV wave: %s from %0t (record %0d of '%s')\", file, $time, cnt[c], names[c]);",
        "            end",
        "            if (want[c] && n_left < 0 && cnt[c] >= at[c]) begin",
        "                n_left = n_after;",
        "                $display(\"OCV wave: record %0d of '%s' at %0t\", at[c], names[c], $time);",
        "            end",
        "        end",
        "        if (n_left == 0) begin",
        "            $dumpflush;",
        "            $display(\"OCV wave: %s written, to %0t\", file, $time);",
        "            $finish;",
        "        end",
        "        if (n_left > 0) n_left--;",
        "    end",
        f"endmodule : {top}_wave",
    ]
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("tb", nargs="+")
    ap.add_argument("--top", default="tb_top")
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()
    try:
        d = parse([open(f).read() for f in a.tb], a.top)
    except TbError as e:
        print(f"tbwave: {e}", file=sys.stderr)
        sys.exit(2)
    open(a.out, "w").write(wrapper(d))


if __name__ == "__main__":
    main()
