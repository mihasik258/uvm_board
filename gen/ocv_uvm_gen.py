def _sv_fields(d):
    """the descriptor with every field's name a legal SystemVerilog identifier"""
    import copy
    d = copy.deepcopy(d)
    for c in d.get("channels", []):
        for f in c.get("fields", []):
            if f["name"] in _SV_KEYWORDS:
                f["name"] += "_f"
    return d


def _rng(w):
    return f"[{w - 1}:0]" if w > 1 else ""


def _ftype(f, signed_ok=True):
    s = " signed" if f.get("signed") and signed_ok else ""
    return f"bit{s} {_rng(f['width'])}".rstrip()


def gen_uvm_pkg(d, src):
    d = _sv_fields(d)
    nm = d["name"]
    L = []
    a = L.append
    a(f"// GENERATED by ocv_gen.py --uvm from {src} - do not edit; regenerate instead.")
    a(f"//")
    a(f"// UVM layer of DUT '{d['module']}': transactions, agents and pin-level drivers/monitors.")
    a(f"// The same agents run in simulation (pins) and on the board (+define+OCV_BOARD: the FPGA).")
    a(f"`ifndef {nm.upper()}_OCV_UVM_PKG_SV")
    a(f"`define {nm.upper()}_OCV_UVM_PKG_SV")
    a('`include "uvm_macros.svh"')
    a("")
    a("`ifndef OCV_BOARD")
    a(f"interface {nm}_ocv_if (input logic clk);")
    a("    logic rst_done;                       // the harness released the DUT's reset")
    cb = []
    for c in d["channels"]:
        cn = c["name"]
        a(f"    logic {cn}_valid;")
        if "ready" in c:
            a(f"    logic {cn}_ready;")
        for f in c["fields"]:
            a(f"    logic {_rng(f['width']):<8} {cn}_{f['name']};")
        if c["kind"] == "source":
            cb.append(f"output {cn}_valid" + "".join(f", {cn}_{f['name']}" for f in c["fields"]))
            if "ready" in c:
                cb.append(f"input {cn}_ready")
        else:
            cb.append(f"input {cn}_valid" + "".join(f", {cn}_{f['name']}" for f in c["fields"]))
            if "ready" in c:
                cb.append(f"output {cn}_ready")
    a("    clocking cb @(posedge clk);")
    a("        default input #1step output #0;")
    for x in cb:
        a(f"        {x};")
    a("    endclocking")
    a(f"endinterface : {nm}_ocv_if")
    a("`endif")
    a("")
    a(f"package {nm}_ocv_uvm_pkg;")
    a("    import uvm_pkg::*;")
    a("    import ocv_uvm_pkg::*;")
    a("")
    for i, c in enumerate(d["channels"]):
        a(f"    localparam int {nm.upper()}_CH_{c['name'].upper()} = {i};")
    a("")
    for i, c in enumerate(d["channels"]):
        cn, ty = c["name"], f"{nm}_{c['name']}_item"
        src_ch = c["kind"] == "source"
        a(f"    // ---- channel '{cn}' ({c['kind']}) ----")
        a(f"    class {ty} extends ocv_item;")
        a(f"        `uvm_object_utils({ty})")
        for f in c["fields"]:
            a(f"        {'rand ' if src_ch else ''}{_ftype(f)} {f['name']};")
        a(f"        function new(string name = \"{ty}\"); super.new(name); endfunction")
        a(f"        virtual function ocv_rec_t to_rec();")
        a(f"            ocv_rec_t r = '0;")
        for f in c["fields"]:
            a(f"            r[{f['lsb']} +: {f['width']}] = {f['name']};")
        a(f"            return r;")
        a(f"        endfunction")
        a(f"        virtual function void from_rec(ocv_rec_t r);")
        for f in c["fields"]:
            a(f"            {f['name']} = r[{f['lsb']} +: {f['width']}];")
        a(f"        endfunction")
        a(f"        virtual function void do_copy(uvm_object rhs);")
        a(f"            {ty} o;")
        a(f"            super.do_copy(rhs);")
        a(f"            if (!$cast(o, rhs)) `uvm_fatal(\"OCV\", \"do_copy: wrong type\")")
        for f in c["fields"]:
            a(f"            {f['name']} = o.{f['name']};")
        a(f"        endfunction")
        a(f"        virtual function string convert2string();")
        a(f"            return $sformatf(\"" + " ".join(f"{f['name']}=%0d" if f.get("signed") else f"{f['name']}=0x%0h"
                                              for f in c["fields"]) + "\", "
          + ", ".join(f["name"] for f in c["fields"]) + ");")
        a(f"        endfunction")
        if not src_ch:
            a(f"        // the descriptor's compare rules; mismatch() names the first differing field")
            a(f"        virtual function string mismatch({ty} o);")
            for f in c["fields"]:
                code, arg, fp = f["cmp"]
                a(f"            if (!ocv_field_match({code}, 64'h{arg:X}, {fp}, {f['width']}, {int(bool(f.get('signed')))}, "
                  f"64'({f['name']}), 64'(o.{f['name']}))) return \"{f['name']}\";")
            a(f"            return \"\";")
            a(f"        endfunction")
            a(f"        virtual function bit do_compare(uvm_object rhs, uvm_comparer comparer);")
            a(f"            {ty} o;")
            a(f"            return $cast(o, rhs) && super.do_compare(rhs, comparer) && mismatch(o) == \"\";")
            a(f"        endfunction")
        a(f"    endclass")
        a("")
        # pin-level driver / monitor
        vif = f"virtual {nm}_ocv_if"
        if src_ch:
            base, cls = f"ocv_source_driver #({ty})", f"{nm}_{cn}_driver"
        else:
            base, cls = f"ocv_monitor #({ty})", f"{nm}_{cn}_monitor"
        a(f"    class {cls} extends {base};")
        a(f"        `uvm_component_utils({cls})")
        a("`ifndef OCV_BOARD")
        a(f"        {vif} vif;")
        a("`endif")
        a(f"        function new(string name, uvm_component parent); super.new(name, parent); endfunction")
        a("`ifndef OCV_BOARD")
        a(f"        function void build_phase(uvm_phase phase);")
        a(f"            super.build_phase(phase);")
        a(f"            if (!uvm_config_db #({vif})::get(this, \"\", \"{nm}_vif\", vif))")
        a(f"                `uvm_fatal(\"OCV\", \"no '{nm}_vif' in the config DB: instantiate {nm}_ocv_uvm_harness\")")
        a(f"        endfunction")
        if src_ch:
            a(f"        virtual task drive({ty} t);")
            a(f"            wait (vif.rst_done);")
            a(f"            vif.cb.{cn}_valid <= 1'b1;")
            for f in c["fields"]:
                a(f"            vif.cb.{cn}_{f['name']} <= t.{f['name']};")
            if "ready" in c:
                a(f"            do @(vif.cb); while (!vif.cb.{cn}_ready);")
            else:
                a(f"            @(vif.cb);")
            a(f"            vif.cb.{cn}_valid <= 1'b0;")
            a(f"        endtask")
        else:
            if "ready" in c:
                a(f"        task run_phase(uvm_phase phase);")
                a(f"            vif.cb.{cn}_ready <= 1'b1;            // always ready in simulation")
                a(f"            super.run_phase(phase);")
                a(f"        endtask")
            # a sink's ready is ours and always 1: valid at an edge is a transfer
            hs = f"vif.cb.{cn}_valid"
            a(f"        virtual task sample(output {ty} t);")
            a(f"            do @(vif.cb); while (!({hs} && vif.rst_done));")
            a(f"            t = {ty}::type_id::create(\"t\");")
            for f in c["fields"]:
                a(f"            t.{f['name']} = vif.cb.{cn}_{f['name']};")
            a(f"        endtask")
        a("`endif")
        a(f"    endclass")
        a("")
        if src_ch:
            a(f"    class {nm}_{cn}_agent extends ocv_source_agent #({ty}, {cls});")
        else:
            a(f"    class {nm}_{cn}_agent extends ocv_output_agent #({ty}, {cls});")
        a(f"        `uvm_component_utils({nm}_{cn}_agent)")
        a(f"        function new(string name, uvm_component parent);")
        a(f"            super.new(name, parent);")
        a(f"            ch = {nm.upper()}_CH_{cn.upper()};")
        a(f"        endfunction")
        a(f"    endclass")
        a("")
    a(f"endpackage : {nm}_ocv_uvm_pkg")
    a("`endif")
    return "\n".join(L) + "\n"


def gen_uvm_harness(d, src, sv_value):
    d = _sv_fields(d)
    nm = d["name"]
    L = []
    a = L.append
    a(f"// GENERATED by ocv_gen.py --uvm from {src} - do not edit; regenerate instead.")
    a(f"//")
    a(f"// {nm}_ocv_uvm_harness: put one in the testbench top. Simulation: clock, reset, DUT "
      f"'{d['module']}',")
    a(f"// its pins as {nm}_ocv_if in the config DB ('{nm}_vif'). Board build (OCV_BOARD): empty - the "
      f"DUT is in the FPGA.")
    a(f"module {nm}_ocv_uvm_harness #(parameter real CLK_PERIOD_NS = 10.0, parameter int RESET_CYCLES = 10);")
    a("`ifndef OCV_BOARD")
    a("    import uvm_pkg::*;")
    a("    logic clk = 1'b0;")
    a("    always #(CLK_PERIOD_NS / 2) clk = ~clk;")
    a(f"    {nm}_ocv_if vif (clk);")
    rst = d.get("reset")
    if rst:
        on = "1'b0" if rst["active"] == "low" else "1'b1"
        off = "1'b1" if rst["active"] == "low" else "1'b0"
        a("    logic rst;")
    a("    initial begin")
    a(f"        uvm_config_db #(virtual {nm}_ocv_if)::set(null, \"*\", \"{nm}_vif\", vif);")
    a("        vif.rst_done = 1'b0;")
    for c in d["channels"]:
        if c["kind"] == "source":
            a(f"        vif.{c['name']}_valid = 1'b0;")
        elif "ready" in c:
            a(f"        vif.{c['name']}_ready = 1'b0;")
    if rst:
        a(f"        rst = {on};")
        a("        repeat (RESET_CYCLES) @(posedge clk);")
        a(f"        rst <= {off};")
    a("        @(posedge clk);")
    a("        vif.rst_done <= 1'b1;")
    a("    end")
    conns = [(d["clock"], "clk")]
    if rst:
        conns.append((rst["port"], "rst"))
    for c in d["channels"]:
        cn = c["name"]
        conns.append((c["valid"], f"vif.{cn}_valid"))
        if "ready" in c:
            conns.append((c["ready"], f"vif.{cn}_ready"))
        if "stall" in c:
            conns.append((c["stall"], "1'b0"))
        for f in c["fields"]:
            conns.append((f["port"], f"vif.{cn}_{f['name']}"))
    for p, v in d.get("tie", {}).items():
        conns.append((p, sv_value(v)))
    for e in d.get("export", []):
        conns.append((e["port"], "'0" if e["dir"] == "in" else ""))
    params = d.get("parameters", {})
    if params:
        a(f"    {d['module']} #(")
        a(",\n".join(f"        .{k} ({sv_value(v)})" for k, v in params.items()))
        a("    ) i_dut (")
    else:
        a(f"    {d['module']} i_dut (")
    w = max(len(p) for p, _ in conns)
    a(",\n".join(f"        .{p:<{w}} ({v})" for p, v in conns))
    a("    );")
    a("`endif")
    a(f"endmodule : {nm}_ocv_uvm_harness")
    return "\n".join(L) + "\n"


def uvm_transform(raw, need):
    """Hub for transactions: sources become streams, monitors lossless; sinks need 'ready'."""
    for c in raw.get("channels", []):
        if c.get("kind") == "source":
            c["stream"] = True
        elif c.get("kind") == "monitor":
            need("stall" not in c, f"channel '{c.get('name')}': --uvm drains monitors without loss; drop 'stall'")
            c["lossless"] = True
        elif c.get("kind") == "sink":
            need("ready" in c, f"channel '{c.get('name')}': --uvm needs the sink's 'ready' (no record may be lost)")
