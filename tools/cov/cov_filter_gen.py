#!/usr/bin/env python3
"""cov_filter_gen.py - the model's record filter table (models/cpu/ocv_cov_filter.c; --model-opt rvfi_filter=<table>)
from a testbench's covergroup sources, not written by hand: the projections and bit-wise fields of every coverpoint
and cross with bins in its configuration (tools/cov/cov_proj.py, from cov_fields.py's fields.json and the harness's
report on no records), the names that move isacov's history (its sample() branches with this configuration's
flags) and Spike's instruction-name table (tools/cov/spike_table.cpp).

    cov_filter_gen.py <fields.json> <bins.rep> <cfg> <spike.tab> > filter.tab
      cfg: a check file of the harness (examples/cva6/cov/cov.sh check: its first line)
"""
import sys

import cov_proj as cp


def main():
    fields, bins, cfg, spike = sys.argv[1:5]
    tab = cp.Table(fields, bins, cfg, spike)
    if tab.unsup:
        sys.exit("cov_filter_gen: fields with no refinement in the filter: %s" % tab.unsup)
    print("# generated by tools/cov/cov_filter_gen.py from %s, %s, %s" % (fields, bins, cfg))
    for pr in tab.projs:
        print("proj " + " ".join(pr))
    print("bit " + " ".join(str(b) for b in tab.bitf))
    for k in ("normal", "ecall_or_ebreak"):
        print("hist %s %s" % (k, " ".join(sorted(tab.hist[k]))))
    for line in open(spike):
        print("insn " + line.rstrip("\n"))


if __name__ == "__main__":
    main()
