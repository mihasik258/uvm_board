#!/usr/bin/env python3
"""gen_no_iss.py - core-v-verif's ISS component (imperas_iss.flist) without the ISS, for a build with no
Imperas licence: the run is the one other simulators make without +USE_ISS, when the ISS is never called.

Imperas's CV32 model is a commercial library behind DPI (svimp_*); its SystemVerilog side does not build
with Verilator (unpacked structs through DPI), nor does the testbench's ISS wrapper (it decodes the ISS's
disassembly for coverage: a ref argument on an array element). Here:
  imperas_CV32.sv        the vendor file with its interfaces (RVVI_bus/io/state/control) as they are and
                         module CPU reduced to its members (state, control, cycles) - no DPI
  uvmt_cv32e40p_iss_wrap the same parameters, ports and instances (bus, io, mon, ram, cpu), no decoding
  ram.sv                 the ISS memory: RVVI_memory with one word, RAM with only that member (idle bus)
  uvmt_cv32e40p_step_compare  ports only: without the ISS there is nothing to compare
  no_iss.flist           imperas_iss.flist with these four files in place of the originals

    gen_no_iss.py <core-v-verif> <out dir>
"""
import os, re, sys

cvv, out = sys.argv[1], sys.argv[2]
os.makedirs(out, exist_ok=True)
src = open(os.path.join(cvv, "vendor_lib/imperas/imperas_DV_COREV/sv/imperas_CV32.sv")).read()
m = re.search(r"^module CPU\b.*?^endmodule\b[^\n]*", src, re.S | re.M)
assert m, "module CPU not found"
hdr = re.match(r"module CPU\s*#\s*\((.*?)\)\s*\((.*?)\)\s*;", m.group(0), re.S)
assert hdr, "CPU header not understood"
cpu = f"""module CPU #({hdr.group(1)}) ({hdr.group(2)});
    // no ISS: the members the testbench refers to, never driven
    RVVI_state   state();
    RVVI_control control();
    bit [31:0]   cycles;
endmodule
"""
open(os.path.join(out, "imperas_CV32.sv"), "w").write(
    "// GENERATED by gen_no_iss.py from vendor_lib/imperas/imperas_DV_COREV/sv/imperas_CV32.sv: module CPU without the ISS\n"
    + src[:m.start()] + cpu + src[m.end():])

wrap = open(os.path.join(cvv, "cv32e40p/tb/uvmt/uvmt_cv32e40p_iss_wrap.sv")).read()
w = re.search(r"^module uvmt_cv32e40p_iss_wrap\b.*?\)\s*;", wrap, re.S | re.M)
inst = re.search(r"^\s*RVVI_bus\s+bus\(\);.*?CPU\s*#\s*\(.*?\)\s*cpu\s*\(bus,\s*io\);", wrap, re.S | re.M)
assert w and inst, "iss_wrap not understood"
open(os.path.join(out, "uvmt_cv32e40p_iss_wrap.sv"), "w").write(
    "// GENERATED by gen_no_iss.py from cv32e40p/tb/uvmt/uvmt_cv32e40p_iss_wrap.sv: the ISS wrapper without the ISS\n"
    + w.group(0) + "\n" + inst.group(0) + "\n   assign bus.Clk = clknrst_if.clk;\nendmodule : uvmt_cv32e40p_iss_wrap\n")

# the ISS's memory: an associative array written through a virtual interface (Verilator cannot trigger
# on that type); without the ISS nothing reads it - the testbench only mirrors into it the values its
# rand-num virtual peripheral gives the core, for the ISS to read - so one word stands in for it (those
# writes land out of its range and are dropped)
ram = open(os.path.join(cvv, "vendor_lib/imperas/design/ram.sv")).read()
decl = "    reg [31:0] mem [bit[29:0]];"
assert ram.count(decl) == 1, "RVVI_memory not understood"
ram = ram.replace(decl, "    reg [31:0] mem [1];   // no ISS: never read (gen_no_iss.py)")
rm = re.search(r"^module RAM\b.*?^endmodule\b[^\n]*", ram, re.S | re.M)
rh = rm and re.match(r"module RAM\s*#\s*\((.*?)\)\s*\((.*?)\)\s*;", rm.group(0), re.S)
assert rh, "module RAM not understood"
open(os.path.join(out, "ram.sv"), "w").write(
    "// GENERATED by gen_no_iss.py from vendor_lib/imperas/design/ram.sv: the ISS memory without the ISS\n"
    + ram[:rm.start()] + f"module RAM #({rh.group(1)}) ({rh.group(2)});\n    RVVI_memory memory();   // no ISS: the bus is idle\nendmodule\n"
    + ram[rm.end():])

# step-and-compare: without the ISS it only prints that random stalls are on; its 'always @(*)' with
# timing controls inside spins at time 0 in Verilator 5.052 (the implicit sensitivity is lost when the
# block becomes a coroutine), so the module is kept with its ports and no body
sc = open(os.path.join(cvv, "cv32e40p/tb/uvmt/uvmt_cv32e40p_step_compare.sv")).read()
sh = re.search(r"^module uvmt_cv32e40p_step_compare\b.*?\)\s*;", sc, re.S | re.M)
assert sh, "step_compare not understood"
open(os.path.join(out, "uvmt_cv32e40p_step_compare.sv"), "w").write(
    "// GENERATED by gen_no_iss.py from cv32e40p/tb/uvmt/uvmt_cv32e40p_step_compare.sv: no ISS, nothing to compare\n"
    + sh.group(0) + "\nendmodule : uvmt_cv32e40p_step_compare\n")

fl = open(os.path.join(cvv, "cv32e40p/tb/uvmt/imperas_iss.flist")).read()
fl = fl.replace("${TBSRC_HOME}/uvmt/uvmt_cv32e40p_step_compare.sv", os.path.join(out, "uvmt_cv32e40p_step_compare.sv"))
fl = fl.replace("${DV_OVPM_DESIGN}/ram.sv", os.path.join(out, "ram.sv"))
fl = fl.replace("${TBSRC_HOME}/uvmt/uvmt_cv32e40p_iss_wrap.sv", os.path.join(out, "uvmt_cv32e40p_iss_wrap.sv"))
fl = fl.replace("${DV_OVPM_MODEL}/sv/imperas_CV32.sv", os.path.join(out, "imperas_CV32.sv"))
open(os.path.join(out, "no_iss.flist"), "w").write(fl)
